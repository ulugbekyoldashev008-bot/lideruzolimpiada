    positions = (2, 0, 3, 1)
    result = []
    for index, (question, correct, wrong_1, wrong_2, wrong_3) in enumerate(rows):
        answer_index = positions[index % len(positions)]
        options = [wrong_1, wrong_2, wrong_3]
        options.insert(answer_index, correct)
        result.append((question, options, answer_index))
    return result


